// Returns a pointer to the R element in an RGB triplet, given a normalized in [-1,1] range value
const uint8_t *dwr3::colormap_rgb_from_normalized(const float norm) {
    int i = static_cast<int>(roundf((norm + 1.0f) / 2.0f * static_cast<float>(colormap_size) - 0.5f));
    if (i >= colormap_size) i = colormap_size - 1;
    else if (i < 0) i = 0;
    return colormap_data + i * 3;
}
